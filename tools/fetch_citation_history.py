#!/usr/bin/env python3
"""Write the cumulative citation history drawn in the publications plot.

Two series, both from INSPIRE-HEP's citations-by-year facet -- the same one
behind the "Citations per year" graph on an author's INSPIRE profile:

  all       every paper of the author named in LL_InspireData.tex
  selected  the papers this CV lists, by the collection query the
            inspirehep-latex fetcher writes to that same file

These are citations, not citing papers.  The inspirehep-latex year series count
a citing paper once however many of the listed papers it cites, which for a
collaboration author is several times fewer than the citation totals the CV
quotes beside the plot.

Run it after inspirehep-fetch.py, which supplies the author and the query.  If
INSPIRE cannot be reached the existing output is left alone, as the fetcher
does, so an offline build still has a plot.

Usage:  tools/fetch_citation_history.py [--data LL_InspireData.tex]
                                        [--output LL_CitationHistory.tex]
                                        [--strict]
"""

from __future__ import annotations

import argparse
import datetime
import json
import re
import sys
import urllib.parse
import urllib.request

API = "https://inspirehep.net/api"
USER_AGENT = "LL_CV citation history (https://github.com/lawrenceleejr/LL_CV)"

# The window opens in 2010.  INSPIRE attributes a handful of citations to the
# 2000s -- about twenty in all, before the first paper -- and on a log axis they
# would stretch a flat tail across half the plot.  They still count: each point
# is the running total since the first citation, so 2010 starts from them.
FIRST_YEAR = 2010


def api_get(path: str, params: dict[str, str]) -> dict:
    url = f"{API}/{path}?{urllib.parse.urlencode(params)}"
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.load(response)


def bai_of(author_id: str) -> str:
    profile = api_get(f"authors/{author_id}", {"fields": "ids"})
    bais = [i["value"] for i in profile["metadata"].get("ids", [])
            if i.get("schema") == "INSPIRE BAI"]
    if not bais:
        raise RuntimeError(f"author {author_id} has no INSPIRE BAI")
    return bais[0]


def citations_by_year(query: str) -> dict[int, int]:
    facets = api_get("literature/facets", {"q": query, "facet_name": "citations-by-year"})
    value = facets["aggregations"]["citations_by_year"]["value"]
    if not value:
        raise RuntimeError(f"no citations by year for {query[:60]!r}")
    return {int(year): int(count) for year, count in value.items()}


def cumulative(per_year: dict[int, int], through: int) -> str:
    """pgfplots coordinates for the running total, one point per year from the
    later of FIRST_YEAR and the first citation, through the current year."""
    points, total = [], 0
    for year in range(min(per_year), through + 1):
        total += per_year.get(year, 0)
        if year >= FIRST_YEAR:
            points.append(f"({year},{total})")
    return " ".join(points)


def read_inputs(data_path: str) -> tuple[str, str]:
    text = open(data_path, encoding="utf-8").read()
    authors = sorted(set(re.findall(r"\\inspiresetauthorstat\{(\d+)\}", text)))
    if len(authors) != 1:
        raise RuntimeError(f"expected one author in {data_path}, found {authors or 'none'}")
    query = re.search(r"\\inspiresetcollectionquery\{([^}]*)\}", text)
    if not query:
        raise RuntimeError(f"no collection query in {data_path}")
    return authors[0], urllib.parse.unquote_plus(query.group(1))


def render(all_series: str, selected_series: str, today: datetime.date) -> str:
    # Each series is wrapped in a command that takes the plot options, so the
    # coordinates reach \addplot as literal tokens: pgfplots does not expand a
    # macro handed to `coordinates'.
    return (
        "% Generated by tools/fetch_citation_history.py -- do not edit by hand.\n"
        f"% Cumulative INSPIRE-HEP citations at the end of each year, fetched {today.isoformat()}.\n"
        f"\\newcommand{{\\LLaddcitesall}}[1]{{\\addplot[#1] coordinates {{{all_series}}}}}\n"
        f"\\newcommand{{\\LLaddcitesselected}}[1]{{\\addplot[#1] coordinates {{{selected_series}}}}}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--data", default="LL_InspireData.tex")
    parser.add_argument("--output", default="LL_CitationHistory.tex")
    parser.add_argument("--strict", action="store_true",
                        help="fail instead of keeping the existing output")
    args = parser.parse_args()

    today = datetime.date.today()
    try:
        author_id, collection_query = read_inputs(args.data)
        all_years = citations_by_year(f"a {bai_of(author_id)}")
        selected_years = citations_by_year(collection_query)
    except Exception as error:  # network, API shape, or missing inputs alike
        print(f"citation history: not updated ({error})", file=sys.stderr)
        return 1 if args.strict else 0

    content = render(cumulative(all_years, today.year),
                     cumulative(selected_years, today.year), today)
    with open(args.output, "w", encoding="utf-8") as out:
        out.write(content)
    print(f"citation history: {sum(all_years.values()):,} citations in all, "
          f"{sum(selected_years.values()):,} to the selected papers -> {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
